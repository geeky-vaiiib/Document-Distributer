def describe_document(row, today):
    document = dict(row)
    document.update(days=None, expiry=None, status="none")
    if row["expiry_date"]:
        try:
            expiry = date.fromisoformat(row["expiry_date"])
        except ValueError:
            document["status"] = "invalid"
        else:
            days = (expiry - today).days
            document.update(
                days=days, expiry=expiry,
                status="expired" if days < 0 else "soon" if days <= 30 else "valid",
            )
    document["file_type"] = (
        "PDF" if document["file_name"].startswith(DEMO_PREFIX)
        else Path(document["file_name"]).suffix.upper().lstrip(".")
    )
    return document


@app.template_filter("friendly_date")
def friendly_date(value):
    if not value:
        return "—"
    try:
        day = date.fromisoformat(value)
    except ValueError:
        return value
    return f"{day:%b} {day.day}, {day.year}"


@app.get("/dashboard")
@app.get("/documents", endpoint="documents")
@app.get("/reminders", endpoint="reminders")
def dashboard():
    if not g.workspace:
        return redirect(url_for("login"))
    section = request.path.strip("/")
    with connect() as con:
        rows = con.execute(
            "SELECT * FROM documents WHERE student_id = ? ORDER BY id DESC",
            (g.workspace,),
        ).fetchall()
    today = date.today()
    all_docs = [describe_document(row, today) for row in rows]
    counts = {key: sum(doc["status"] == key for doc in all_docs) for key in STATUSES}
    attention = sorted(
        (doc for doc in all_docs if doc["status"] in ("soon", "expired")),
        key=lambda doc: (doc["status"] != "soon", abs(doc["days"])),
    )
    search = request.args.get("search", "").strip()[:150]
    search_key = search.casefold()
    category = request.args.get("category", "")
    status = request.args.get("status", "")
    sort = request.args.get("sort", "recent")
    docs = [
        doc for doc in all_docs
        if (search_key in doc["document_name"].casefold()
            or search_key in doc["category"].casefold()
            or search_key in CATEGORY_LABELS.get(doc["category"], "").casefold())
        and (category not in CATEGORIES or doc["category"] == category)
        and (status not in STATUSES or doc["status"] == status)
    ]
    if sort == "expiry":
        docs.sort(key=lambda doc: (doc["expiry"] is None, doc["expiry"]))
    elif sort == "name":
        docs.sort(key=lambda doc: doc["document_name"].casefold())
    return render_template(
        "dashboard.html", section=section, docs=docs, total=len(all_docs), counts=counts,
        attention=attention, categories=CATEGORIES, search=search,
        category=category, status=status, sort=sort, today=today,
    )


def owned_document(con, document_id):
    row = con.execute(
        "SELECT * FROM documents WHERE id = ? AND student_id = ?",
        (document_id, g.workspace),
    ).fetchone()
    if row is None:
        abort(404)
    return row


def read_upload(upload):
    suffix = Path(upload.filename).suffix.lower()
    if suffix not in FILE_TYPES:
        raise ValueError("Choose a PDF, PNG, JPG or JPEG file.")
    file_data = upload.stream.read(MAX_FILE_SIZE + 1)
    if len(file_data) > MAX_FILE_SIZE:
        raise ValueError("Choose a file that is 10 MB or smaller.")
    if not file_data.startswith(FILE_TYPES[suffix][1]):
        raise ValueError("The file contents don’t match the selected file type.")
    return f"{uuid4().hex}{suffix}", file_data


def store_upload(con, filename, contents, previous_filename):
    if app.config["DATABASE_URL"]:
        stored = con.execute(
            "SELECT COALESCE(SUM(size_bytes), 0) AS total FROM document_files WHERE file_name <> ?",
            (previous_filename or "",),
        ).fetchone()["total"]
        if stored + len(contents) > HOSTED_FILE_BUDGET:
            raise ValueError("Storage is full. Delete unused documents before uploading.")
    con.execute(
        "INSERT INTO document_files (file_name, contents, size_bytes) VALUES (?, ?, ?)",
        (filename, contents, len(contents)),
    )


def remove_legacy_upload(filename):
    if not app.config["DATABASE_URL"] and filename and not filename.startswith(DEMO_PREFIX):
        try:
            (app.config["UPLOAD_DIR"] / Path(filename).name).unlink(missing_ok=True)
        except OSError:
            app.logger.exception("Could not remove document file")


@app.route("/add-document", methods=["GET", "POST"])
@app.route("/documents/<int:document_id>/edit", methods=["GET", "POST"])
def document_form(document_id=None):
    if not g.workspace:
        return redirect(url_for("login"))
    current = None
    if document_id is not None:
        with connect() as con:
            current = owned_document(con, document_id)
    values = dict(current) if current else {}
    if request.method == "POST":
        values = {name: request.form.get(name, "").strip() for name in
                  ("document_name", "category", "issue_date", "expiry_date")}
        filename = None
        previous_filename = None
        try:
            name, category = values["document_name"], values["category"]
            if not name or len(name) > 120 or not name.isprintable():
                raise ValueError("Enter a document name between 1 and 120 characters.")
            if category not in CATEGORIES:
                raise ValueError("Choose a category from the list.")
            issue = parse_form_date(values["issue_date"])
            expiry = parse_form_date(values["expiry_date"])
            if issue and expiry and expiry < issue:
                raise ValueError("The expiry date must be on or after the issue date.")
            upload = request.files.get("document")
            if upload and upload.filename:
                filename, contents = read_upload(upload)
            elif current is None:
                raise ValueError("Choose a file to upload.")
            with connect() as con:
                begin_write(con)
                if current:
                    previous_filename = owned_document(con, document_id)["file_name"]
                if filename:
                    store_upload(con, filename, contents, previous_filename)
                if current:
                    con.execute(
                        """UPDATE documents SET document_name = ?, category = ?, issue_date = ?,
                           expiry_date = ?, file_name = ? WHERE id = ? AND student_id = ?""",
                        (name, category, issue, expiry, filename or previous_filename,
                         document_id, g.workspace),
                    )
                    if filename:
                        con.execute("DELETE FROM document_files WHERE file_name = ?", (previous_filename,))
                else:
                    con.execute(
                        """INSERT INTO documents
                           (student_id, document_name, category, issue_date, expiry_date, file_name)
                           VALUES (?, ?, ?, ?, ?, ?)""",
                        (g.workspace, name, category, issue, expiry, filename),
                    )
        except ValueError as error:
            flash(str(error), "error")
            return render_template(
                "add_document.html", values=values, current=current, categories=CATEGORIES,
            ), 400
        if filename:
            remove_legacy_upload(previous_filename)
        flash("Document updated." if current else "Document added.", "success")
        return redirect(url_for("documents"))
    return render_template(
        "add_document.html", values=values, current=current, categories=CATEGORIES,
    )


def parse_form_date(value):
    if not value:
        return None
    try:
        return date.fromisoformat(value).isoformat()
    except ValueError as error:
        raise ValueError("Enter a valid issue and expiry date.") from error


