class PostgresConnection:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, sql, parameters=()):
        return self.connection.execute(sql.replace("?", "%s"), parameters)

    def executemany(self, sql, parameters):
        with self.connection.cursor() as cursor:
            cursor.executemany(sql.replace("?", "%s"), parameters)


@contextmanager
def connect():
    if app.config["DATABASE_URL"]:
        import psycopg
        from psycopg.rows import dict_row

        with psycopg.connect(app.config["DATABASE_URL"], row_factory=dict_row, connect_timeout=10) as con:
            yield PostgresConnection(con)
        return

    con = sqlite3.connect(app.config["DATABASE"])
    con.row_factory = sqlite3.Row
    try:
        con.execute("PRAGMA foreign_keys = ON")
        with con:
            yield con
    finally:
        con.close()


def init_db():
    postgres = bool(app.config["DATABASE_URL"])
    if not postgres:
        app.config["DATABASE"].parent.mkdir(parents=True, exist_ok=True)
        app.config["UPLOAD_DIR"].mkdir(parents=True, exist_ok=True)
    primary_key = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if postgres else "INTEGER PRIMARY KEY AUTOINCREMENT"
    binary_type = "BYTEA" if postgres else "BLOB"
    with connect() as con:
        begin_write(con)
        schema = f"""
            CREATE TABLE IF NOT EXISTS students (
                id {primary_key},
                student_name TEXT NOT NULL,
                email TEXT UNIQUE NOT NULL,
                password TEXT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS documents (
                id {primary_key},
                student_id INTEGER NOT NULL REFERENCES students(id),
                document_name TEXT NOT NULL,
                category TEXT NOT NULL,
                issue_date TEXT,
                expiry_date TEXT,
                file_name TEXT NOT NULL
            );
            CREATE INDEX IF NOT EXISTS documents_student ON documents(student_id);
            CREATE TABLE IF NOT EXISTS document_files (
                file_name TEXT PRIMARY KEY,
                contents {binary_type} NOT NULL,
                size_bytes INTEGER NOT NULL
            );
            CREATE TABLE IF NOT EXISTS app_settings (
                name TEXT PRIMARY KEY,
                value TEXT NOT NULL
            );
        """
        for statement in schema.split(";"):
            if statement.strip():
                con.execute(statement)
        con.execute(
            "INSERT INTO app_settings VALUES (?, ?) ON CONFLICT(name) DO NOTHING",
            ("session_key", secrets.token_hex(32)),
        )
        app.secret_key = SESSION_KEY or con.execute(
            "SELECT value FROM app_settings WHERE name = 'session_key'"
        ).fetchone()["value"]


def begin_write(con):
    if app.config["DATABASE_URL"]:
        con.execute("SELECT pg_advisory_xact_lock(1329871010)")
    else:
        con.execute("BEGIN IMMEDIATE")


@app.before_request
def load_workspace():
    if request.endpoint in ("static", "health"):
        return
    g.workspace = session.get("workspace") if session.get("signed_in") else None
    if request.method == "POST":
        token = session.get("csrf_token")
        supplied = request.form.get("csrf_token", "")
        if not token or not secrets.compare_digest(token.encode(), supplied.encode()):
            abort(400)


