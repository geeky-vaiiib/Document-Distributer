def start_session(workspace, student_name):
    demo_id = session.get("demo_id")
    session.clear()
    if demo_id:
        session["demo_id"] = demo_id
    session.permanent = True
    session.update(workspace=workspace, signed_in=True, student_name=student_name)
    return redirect(url_for("dashboard"))


