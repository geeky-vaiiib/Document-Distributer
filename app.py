@app.get("/uploads/<path:filename>")
def uploaded_file(filename):
    if not g.workspace:
        return redirect(url_for("login"))
    with connect() as con:
        document = con.execute(
            """SELECT documents.document_name, document_files.contents
               FROM documents LEFT JOIN document_files USING (file_name)
               WHERE student_id = ? AND file_name = ?""",
            (g.workspace, filename),
        ).fetchone()
    if not document:
        abort(404)
    if filename.startswith(DEMO_PREFIX):
        source = sample_pdf(document["document_name"])
        suffix = ".pdf"
    elif document["contents"] is not None:
        source = io.BytesIO(document["contents"])
        suffix = Path(filename).suffix.lower()
        if suffix not in FILE_TYPES:
            abort(404)
    elif not app.config["DATABASE_URL"]:
        source = app.config["UPLOAD_DIR"] / Path(filename).name
        suffix = source.suffix.lower()
        if not source.is_file() or suffix not in FILE_TYPES:
            abort(404)
    else:
        abort(404)
    download_name = document["document_name"].replace("/", "-").replace("\\", "-")
    try:
        response = send_file(
            source, mimetype=FILE_TYPES[suffix][0], download_name=f"{download_name}{suffix}",
            as_attachment=request.args.get("download") == "1", max_age=0,
        )
    except FileNotFoundError:
        abort(404)
    response.headers.update({
        "Cache-Control": "private, no-store",
        "X-Content-Type-Options": "nosniff",
    })
    return response


def sample_pdf(title):
    def pdf_text(value):
        return value.encode("ascii", "replace").replace(
            b"\\", b"\\\\"
        ).replace(b"(", b"\\(").replace(b")", b"\\)").replace(b"\n", b" ")

    stream = (
        b"BT /F1 23 Tf 56 732 Td (Student Document Organizer) Tj "
        b"/F1 17 Tf 0 -46 Td (" + pdf_text(title) + b") Tj "
        b"/F1 11 Tf 0 -32 Td (Sample student document.) Tj ET"
    )
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
        b"/Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        b"<< /Length %d >>\nstream\n" % len(stream) + stream + b"\nendstream",
    ]
    output = io.BytesIO()
    output.write(b"%PDF-1.4\n")
    offsets = []
    for index, content in enumerate(objects, 1):
        offsets.append(output.tell())
        output.write(b"%d 0 obj\n" % index + content + b"\nendobj\n")
    xref = output.tell()
    output.write(b"xref\n0 6\n0000000000 65535 f \n")
    for offset in offsets:
        output.write(b"%010d 00000 n \n" % offset)
    output.write(b"trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % xref)
    output.seek(0)
    return output


@app.get("/documents/<int:document_id>/calendar.ics")
def calendar_reminder(document_id):
    if not g.workspace:
        return redirect(url_for("login"))
    with connect() as con:
        document = describe_document(owned_document(con, document_id), date.today())
    expiry = document["expiry"]
    if not expiry:
        abort(404)
    name = document["document_name"].replace("\\", "\\\\").replace(
        "\r\n", "\n"
    ).replace("\r", "\n").replace("\n", "\\n").replace(",", "\\,").replace(";", "\\;")
    lines = [
        "BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//Student Document Organizer//EN",
        "BEGIN:VEVENT", f"UID:document-{document_id}@student-organizer.local",
        f"DTSTAMP:{datetime.now(timezone.utc):%Y%m%dT%H%M%SZ}",
        f"DTSTART;VALUE=DATE:{expiry:%Y%m%d}", f"SUMMARY:{name} expires",
    ]
    for days in (30, 7):
        lines.extend(("BEGIN:VALARM", f"TRIGGER:-P{days}D", "ACTION:DISPLAY",
                      "DESCRIPTION:Review your document expiry", "END:VALARM"))
    lines.extend(("END:VEVENT", "END:VCALENDAR", ""))
    folded_lines = []
    for line in lines:
        part = ""
        for char in line:
            if len((part + char).encode()) > 75:
                folded_lines.append(part)
                part = " "
            part += char
        folded_lines.append(part)
    return send_file(
        io.BytesIO("\r\n".join(folded_lines).encode()), mimetype="text/calendar",
        download_name=f"document-{document_id}-expiry.ics", as_attachment=True,
    )


