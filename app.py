@app.route("/", methods=["GET", "POST"])
@app.route("/register", methods=["GET", "POST"], endpoint="register")
def login():
    if g.workspace:
        return redirect(url_for("dashboard"))
    registering = request.endpoint == "register"
    if request.method == "GET":
        return render_template("auth.html", registering=registering, errors={})

    student_name = request.form.get("student_name", "").strip() if registering else ""
    email = request.form.get("email", "").strip().casefold()
    password = request.form.get("password", "")
    errors = {}
    if registering and (not 1 <= len(student_name) <= 100 or not student_name.isprintable()):
        errors["student_name"] = "Enter a student name between 1 and 100 characters."
    if (len(email) > 254 or not email.isprintable() or email.endswith("@demo.invalid")
            or not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", email)):
        errors["email"] = "Enter a valid email address."
    if not password.strip():
        errors["password"] = "Enter a password."
    elif len(password) > 128 or (registering and len(password) < 8):
        errors["password"] = "Use a password between 8 and 128 characters."
    status = 400
    if not errors:
        if registering:
            password_hash = generate_password_hash(password, method=PASSWORD_HASH_METHOD)
            with connect() as con:
                student = con.execute(
                    "INSERT INTO students (student_name, email, password) VALUES (?, ?, ?) "
                    "ON CONFLICT(email) DO NOTHING RETURNING id",
                    (student_name, email, password_hash),
                ).fetchone()
            if student:
                return start_session(student["id"], student_name)
            errors["email"] = "This email address is already registered."
            status = 409
        else:
            with connect() as con:
                student = con.execute(
                    "SELECT id, student_name, password FROM students WHERE email = ?", (email,)
                ).fetchone()
            if student and check_password_hash(student["password"], password):
                return start_session(student["id"], student["student_name"])
            errors["login"] = "The email or password is incorrect."
            status = 401
    return render_template(
        "auth.html", registering=registering, errors=errors,
        name_value=student_name[:100], email=email[:254],
    ), status


@app.post("/demo")
def open_demo():
    if g.workspace:
        return redirect(url_for("dashboard"))
    workspace_email = f"{session.get('demo_id') or uuid4().hex}@demo.invalid"
    with connect() as con:
        begin_write(con)
